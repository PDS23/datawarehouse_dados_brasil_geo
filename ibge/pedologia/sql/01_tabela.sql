-- Pedologia (BDiA, IBGE, 1:250.000) como ESPELHO VERSIONADO: vetorial.ibge_pedologia. Idempotente.
-- Rodar como postgres (o etl so tem DML):
--   .\infra\scripts\dw.ps1 psql -Arquivo ibge\pedologia\sql\01_tabela.sql
--
-- Mapa de solos do Brasil (pedologia) do BDiA, 1:250.000: associações de solos por polígono. Colunas com os nomes do shapefile em minusculas; os campos que o IBGE grava como numero
-- decimal mas sao codigos inteiros viram integer. Chave: id1 (id da feicao no shapefile). Mesmas regras das outras fontes: vigente = vigente_ate IS NULL; nada e apagado na coleta.

INSERT INTO dim.fontes (nome, sigla, url, descricao)
SELECT 'IBGE', 'IBGE', 'https://www.ibge.gov.br', 'Instituto Brasileiro de Geografia e Estatistica'
WHERE NOT EXISTS (SELECT 1 FROM dim.fontes WHERE nome = 'IBGE');

CREATE TABLE IF NOT EXISTS vetorial.ibge_pedologia (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id1           bigint NOT NULL,   -- fonte: id1 - ID da feição no shapefile do IBGE (a chave; único dentro da edição).
    cd_fcim       text,              -- fonte: cd_fcim - Código da folha da Carta Internacional do Mundo ao Milionésimo (CIM) em que a feição está.
    nom_unidad    text,              -- fonte: nom_unidad - Nome (símbolo) da unidade de mapeamento de solos.
    cod_simbol    text,              -- fonte: cod_simbol - Código-símbolo da classe de solo dominante.
    val_ncompo    integer,           -- fonte: val_ncompo - Número de componentes (solos) da associação.
    legenda       text,              -- fonte: legenda - Legenda do solo dominante (símbolo e classe).
    ordem         text,              -- fonte: ordem - Ordem do solo (SiBCS: Neossolo, Latossolo, Argissolo...).
    subordem      text,              -- fonte: subordem - Subordem do solo.
    grande_gru    text,              -- fonte: grande_gru - Grande grupo do solo.
    subgrupos     text,              -- fonte: subgrupos - Subgrupo do solo.
    textura       text,              -- fonte: textura - Textura.
    horizonte     text,              -- fonte: horizonte - Horizonte superficial.
    erosao        text,              -- fonte: erosao - Fase de erosão.
    pedregosid    text,              -- fonte: pedregosid - Fase de pedregosidade.
    rochosidad    text,              -- fonte: rochosidad - Fase de rochosidade.
    relevo        text,              -- fonte: relevo - Fase de relevo.
    componente    text,              -- fonte: componente - Componente principal da unidade (classe completa).
    component1    text,              -- fonte: component1 - Segundo componente da associação.
    component2    text,              -- fonte: component2 - Terceiro componente da associação.
    component3    text,              -- fonte: component3 - Quarto componente da associação.
    inclu_p1      text,              -- fonte: inclu_p1 - Inclusão 1 (solo que ocorre em pequena parte da unidade).
    inclu_p2      text,              -- fonte: inclu_p2 - Inclusão 2.
    inclu_p3      text,              -- fonte: inclu_p3 - Inclusão 3.
    ar_poli_km    numeric,           -- fonte: ar_poli_km - Área do polígono em km² segundo o IBGE.
    leg_ordem     text,              -- fonte: leg_ordem - Ordem do solo da legenda.
    legenda_2     text,              -- fonte: legenda_2 - Legenda do segundo nível (ordem e subordem).
    cd_ord_id     integer,           -- fonte: cd_ord_id - Código da ordem do solo.
    cd_leg2_id    integer,           -- fonte: cd_leg2_id - Código da legenda de segundo nível.
    geom              geometry(MultiPolygon, 4674),   -- fonte: shapefile (SIRGAS 2000). NULL se geom_anomala
    geom_anomala      boolean     NOT NULL DEFAULT false,
    geom_origem_texto text,
    edicao            text        NOT NULL,                       -- derivado: edicao do BDiA (ano da pasta versao_AAAA) em que esta versao entrou
    id_fonte          smallint    NOT NULL REFERENCES dim.fontes (id_fonte),
    importado_em      date        NOT NULL DEFAULT current_date,
    vigente_desde     date        NOT NULL DEFAULT current_date,
    vigente_ate       date,
    coletado_em       timestamptz NOT NULL DEFAULT now(),
    reaberto_em       date
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_ibge_pedologia_vigente ON vetorial.ibge_pedologia (id1) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_ibge_pedologia_geom ON vetorial.ibge_pedologia USING gist (geom) WHERE vigente_ate IS NULL;

COMMENT ON TABLE vetorial.ibge_pedologia IS
    'Pedologia do BDiA (IBGE), 1:250.000. Espelho versionado, uma edicao por pasta versao_AAAA do IBGE. Ver ibge/pedologia/LEIAME_pedologia.md.';
COMMENT ON COLUMN vetorial.ibge_pedologia.id1 IS 'Origem: id1. ID da feicao no shapefile do IBGE (chave; unico dentro da edicao).';
COMMENT ON COLUMN vetorial.ibge_pedologia.edicao IS 'Edicao do BDiA (ano da pasta versao_AAAA) em que esta versao entrou.';

INSERT INTO catalogo.mapa_colunas (tabela, coluna, origem, fonte, observacao)
SELECT 'vetorial.ibge_pedologia', c.column_name,
       CASE WHEN c.column_name = 'edicao' THEN 'derivado'
            WHEN c.column_name IN ('id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala','geom_origem_texto') THEN 'controle'
            WHEN c.column_name = 'geom' THEN 'geometria' ELSE c.column_name END,
       CASE WHEN c.column_name IN ('edicao','id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala') THEN 'pipeline' ELSE 'IBGE' END,
       NULL
FROM information_schema.columns c
WHERE c.table_schema = 'vetorial' AND c.table_name = 'ibge_pedologia'
ON CONFLICT (tabela, coluna) DO UPDATE SET origem = EXCLUDED.origem, fonte = EXCLUDED.fonte;

GRANT SELECT, INSERT, UPDATE, DELETE ON vetorial.ibge_pedologia TO etl;      -- DELETE: so para a rotina de retencao
GRANT SELECT ON vetorial.ibge_pedologia TO leitura, geoserver, analistas;
GRANT MAINTAIN ON vetorial.ibge_pedologia TO etl;

SELECT 'vetorial.ibge_pedologia' AS item, count(*)::text AS valor FROM vetorial.ibge_pedologia;
