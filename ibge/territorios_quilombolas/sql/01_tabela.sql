-- Territorios quilombolas oficialmente delimitados (IBGE) como ESPELHO VERSIONADO: vetorial.ibge_territorios_quilombolas. Idempotente.
-- Rodar como postgres (o etl so tem DML):
--   .\infra\scripts\dw.ps1 psql -Arquivo ibge\territorios_quilombolas\sql\01_tabela.sql
--
-- Camada `CGMAT:qg_AAAA_620_territorioquilombola__vNN` do servidor de mapas do IBGE (poligonos). Colunas com os nomes da fonte; texto sempre `text`.
-- Chave: cd_recorte (codigo do quadro + codigo do territorio, ex.: 6200055). Mesmas regras das outras fontes vivas: vigente = vigente_ate IS NULL;
-- nada e apagado na coleta.

INSERT INTO dim.fontes (nome, sigla, url, descricao)
SELECT 'IBGE', 'IBGE', 'https://www.ibge.gov.br', 'Instituto Brasileiro de Geografia e Estatistica'
WHERE NOT EXISTS (SELECT 1 FROM dim.fontes WHERE nome = 'IBGE');

CREATE TABLE IF NOT EXISTS vetorial.ibge_territorios_quilombolas (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cd_recorte     text        NOT NULL,                  -- fonte: cd_recorte (quadro + cd_tq; chave estavel do territorio)
    cd_tq          text,                                  -- fonte: cd_tq (codigo do territorio quilombola)
    nm_tq          text,                                  -- fonte: nm_tq (nome do territorio)
    status         text,                                  -- fonte: status (fase do processo, ex.: TITULADO)
    quadro         text,                                  -- fonte: quadro (codigo do quadro tematico do IBGE, 620)
    cd_uf          text,                                  -- fonte: cd_uf (codigo IBGE da UF)
    sg_uf          text,                                  -- fonte: sg_uf (sigla da UF)
    id_estado      smallint REFERENCES dim.estados (id_estado),   -- derivado de sg_uf quando a UF existe em dim.estados
    camada_origem  text,                                  -- nome da camada do IBGE de onde veio (traz o ano e a versao)
    geom           geometry(MultiPolygon, 4674),          -- fonte: geometria (SIRGAS 2000). NULL quando geom_anomala
    geom_anomala   boolean     NOT NULL DEFAULT false,
    geom_origem_texto text,
    id_fonte       smallint    NOT NULL REFERENCES dim.fontes (id_fonte),
    importado_em   date        NOT NULL DEFAULT current_date,
    vigente_desde  date        NOT NULL DEFAULT current_date,
    vigente_ate    date,
    coletado_em    timestamptz NOT NULL DEFAULT now(),
    reaberto_em    date
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_ibge_tq_vigente ON vetorial.ibge_territorios_quilombolas (cd_recorte) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_ibge_tq_geom ON vetorial.ibge_territorios_quilombolas USING gist (geom) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_ibge_tq_estado ON vetorial.ibge_territorios_quilombolas (id_estado) WHERE vigente_ate IS NULL;

COMMENT ON TABLE vetorial.ibge_territorios_quilombolas IS
    'Territorios quilombolas oficialmente delimitados, em poligono, do IBGE (camada CGMAT qg_AAAA_620_territorioquilombola). Nao e a base do INCRA. Espelho versionado: vigente = vigente_ate IS NULL. Ver ibge/territorios_quilombolas/LEIAME_territorios_quilombolas.md.';
COMMENT ON COLUMN vetorial.ibge_territorios_quilombolas.cd_recorte IS 'Origem: cd_recorte. Chave estavel; uma versao vigente por territorio.';
COMMENT ON COLUMN vetorial.ibge_territorios_quilombolas.camada_origem IS 'Camada do IBGE usada na coleta (o nome traz o ano e a versao, ex.: qg_2022_620_territorioquilombola__v02).';

