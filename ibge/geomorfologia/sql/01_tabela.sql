-- Geomorfologia (BDiA, IBGE, 1:250.000) como ESPELHO VERSIONADO: vetorial.ibge_geomorfologia. Idempotente.
-- Rodar como postgres (o etl so tem DML):
--   .\infra\scripts\dw.ps1 psql -Arquivo ibge\geomorfologia\sql\01_tabela.sql
--
-- Mapa geomorfológico do Brasil (unidades do relevo) do BDiA, 1:250.000. Colunas com os nomes do shapefile em minusculas; os campos que o IBGE grava como numero
-- decimal mas sao codigos inteiros viram integer. Chave: id1 (id da feicao no shapefile). Mesmas regras das outras fontes: vigente = vigente_ate IS NULL; nada e apagado na coleta.

INSERT INTO dim.fontes (nome, sigla, url, descricao)
SELECT 'IBGE', 'IBGE', 'https://www.ibge.gov.br', 'Instituto Brasileiro de Geografia e Estatistica'
WHERE NOT EXISTS (SELECT 1 FROM dim.fontes WHERE nome = 'IBGE');

CREATE TABLE IF NOT EXISTS vetorial.ibge_geomorfologia (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id1           bigint NOT NULL,   -- fonte: id1 - ID da feição no shapefile do IBGE (a chave; único dentro da edição).
    cd_fcim       text,              -- fonte: cd_fcim - Código da folha da Carta Internacional do Mundo ao Milionésimo (CIM) em que a feição está.
    leg_carga     text,              -- fonte: leg_carga - Código da unidade na legenda da carga original.
    nm_dominio    text,              -- fonte: nm_dominio - Domínio morfoestrutural.
    nm_regiao     text,              -- fonte: nm_regiao - Região geomorfológica.
    id_unidade    integer,           -- fonte: id_unidade - Identificador da unidade geomorfológica.
    nm_unidade    text,              -- fonte: nm_unidade - Nome da unidade geomorfológica.
    letra_simb    text,              -- fonte: letra_simb - Sigla (letra-símbolo) do padrão de relevo.
    categoria     text,              -- fonte: categoria - Categoria do padrão de relevo (ex.: homogênea convexa).
    natureza      text,              -- fonte: natureza - Natureza do processo (dissecação, agradação, aplanamento...).
    caract        text,              -- fonte: caract - Características do relevo.
    forma         text,              -- fonte: forma - Forma do topo ou do modelado (ex.: topo convexo).
    dens_dren     text,              -- fonte: dens_dren - Densidade de drenagem.
    aprof_inci    text,              -- fonte: aprof_inci - Aprofundamento da incisão (entalhe dos vales).
    niv_alt       text,              -- fonte: niv_alt - Nível altimétrico.
    leg_sup       text,              -- fonte: leg_sup - Legenda da unidade superior (região).
    cd_leg_sup    text,              -- fonte: cd_leg_sup - Código da legenda superior.
    legenda       text,              -- fonte: legenda - Legenda completa da unidade.
    ar_poli_km    numeric,           -- fonte: ar_poli_km - Área do polígono em km² segundo o IBGE.
    compartime    text,              -- fonte: compartime - Compartimento do relevo (planaltos, planícies, depressões...).
    cd_comp_id    integer,           -- fonte: cd_comp_id - Código do compartimento.
    cd_dominio    integer,           -- fonte: cd_dominio - Código do domínio morfoestrutural.
    cd_unid_id    integer,           -- fonte: cd_unid_id - Código da unidade geomorfológica.
    geom              geometry(MultiPolygon, 4674),   -- fonte: shapefile (SIRGAS 2000). NULL se geom_anomala
    geom_anomala      boolean     NOT NULL DEFAULT false,
    geom_origem_texto text,
    edicao            text        NOT NULL,                       -- derivado: edicao do BDiA (ano da pasta versao_AAAA) em que esta versao entrou
    id_fonte          smallint    NOT NULL REFERENCES dim.fontes (id_fonte),
    importado_em      date        NOT NULL DEFAULT current_date,
    vigente_desde     date        NOT NULL DEFAULT current_date,
    vigente_ate       date,
    coletado_em       timestamptz NOT NULL DEFAULT now(),
    reaberto_em       date
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_ibge_geomorfologia_vigente ON vetorial.ibge_geomorfologia (id1) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_ibge_geomorfologia_geom ON vetorial.ibge_geomorfologia USING gist (geom) WHERE vigente_ate IS NULL;

COMMENT ON TABLE vetorial.ibge_geomorfologia IS
    'Geomorfologia do BDiA (IBGE), 1:250.000. Espelho versionado, uma edicao por pasta versao_AAAA do IBGE. Ver ibge/geomorfologia/LEIAME_geomorfologia.md.';
COMMENT ON COLUMN vetorial.ibge_geomorfologia.id1 IS 'Origem: id1. ID da feicao no shapefile do IBGE (chave; unico dentro da edicao).';
COMMENT ON COLUMN vetorial.ibge_geomorfologia.edicao IS 'Edicao do BDiA (ano da pasta versao_AAAA) em que esta versao entrou.';

INSERT INTO catalogo.mapa_colunas (tabela, coluna, origem, fonte, observacao)
SELECT 'vetorial.ibge_geomorfologia', c.column_name,
       CASE WHEN c.column_name = 'edicao' THEN 'derivado'
            WHEN c.column_name IN ('id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala','geom_origem_texto') THEN 'controle'
            WHEN c.column_name = 'geom' THEN 'geometria' ELSE c.column_name END,
       CASE WHEN c.column_name IN ('edicao','id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala') THEN 'pipeline' ELSE 'IBGE' END,
       NULL
FROM information_schema.columns c
WHERE c.table_schema = 'vetorial' AND c.table_name = 'ibge_geomorfologia'
ON CONFLICT (tabela, coluna) DO UPDATE SET origem = EXCLUDED.origem, fonte = EXCLUDED.fonte;

GRANT SELECT, INSERT, UPDATE, DELETE ON vetorial.ibge_geomorfologia TO etl;      -- DELETE: so para a rotina de retencao
GRANT SELECT ON vetorial.ibge_geomorfologia TO leitura, geoserver, analistas;
GRANT MAINTAIN ON vetorial.ibge_geomorfologia TO etl;

SELECT 'vetorial.ibge_geomorfologia' AS item, count(*)::text AS valor FROM vetorial.ibge_geomorfologia;
