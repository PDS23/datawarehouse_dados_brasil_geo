-- Vegetação (BDiA, IBGE, 1:250.000) como ESPELHO VERSIONADO: vetorial.ibge_vegetacao. Idempotente.
-- Rodar como postgres (o etl so tem DML):
--   .\infra\scripts\dw.ps1 psql -Arquivo ibge\vegetacao\sql\01_tabela.sql
--
-- Mapa de vegetação do Brasil (cobertura vegetal natural e usos antrópicos) do BDiA, 1:250.000. Colunas com os nomes do shapefile em minusculas; os campos que o IBGE grava como numero
-- decimal mas sao codigos inteiros viram integer. Chave: id1 (id da feicao no shapefile). Mesmas regras das outras fontes: vigente = vigente_ate IS NULL; nada e apagado na coleta.

INSERT INTO dim.fontes (nome, sigla, url, descricao)
SELECT 'IBGE', 'IBGE', 'https://www.ibge.gov.br', 'Instituto Brasileiro de Geografia e Estatistica'
WHERE NOT EXISTS (SELECT 1 FROM dim.fontes WHERE nome = 'IBGE');

CREATE TABLE IF NOT EXISTS vetorial.ibge_vegetacao (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id1           bigint NOT NULL,   -- fonte: id1 - ID da feição no shapefile do IBGE (a chave; único dentro da edição).
    cd_fcim       text,              -- fonte: cd_fcim - Código da folha da Carta Internacional do Mundo ao Milionésimo (CIM) em que a feição está.
    leg_carga     text,              -- fonte: leg_carga - Código da unidade na legenda da carga original.
    cd_fito       text,              -- fonte: cd_fito - Código da região fitoecológica.
    cd_leg_2      text,              -- fonte: cd_leg_2 - Código da legenda de segundo nível.
    clas_domi     text,              -- fonte: clas_domi - Classe dominante (código da vegetação dominante).
    leg_uveg      text,              -- fonte: leg_uveg - Código da unidade de vegetação natural.
    nm_uveg       text,              -- fonte: nm_uveg - Nome da unidade de vegetação natural.
    leg_uantr     text,              -- fonte: leg_uantr - Código da unidade antrópica (uso da terra).
    nm_uantr      text,              -- fonte: nm_uantr - Nome da unidade antrópica (ex.: agropecuária).
    leg_contat    text,              -- fonte: leg_contat - Código do contato entre tipos de vegetação.
    nm_contat     text,              -- fonte: nm_contat - Nome do contato (ex.: ecótono, encrave).
    veg_pretet    text,              -- fonte: veg_pretet - Código da vegetação pretérita (original, antes do uso).
    nm_pretet     text,              -- fonte: nm_pretet - Nome da vegetação pretérita.
    leg_sec1      text,              -- fonte: leg_sec1 - Código da vegetação secundária 1.
    nm_sec1       text,              -- fonte: nm_sec1 - Nome da vegetação secundária 1.
    leg_sec2      text,              -- fonte: leg_sec2 - Código da vegetação secundária 2.
    nm_sec2       text,              -- fonte: nm_sec2 - Nome da vegetação secundária 2.
    leg_sup       text,              -- fonte: leg_sup - Legenda superior (ex.: Vegetação Natural Dominante).
    legenda_1     text,              -- fonte: legenda_1 - Legenda de primeiro nível (formação).
    legenda_2     text,              -- fonte: legenda_2 - Legenda de segundo nível.
    legenda       text,              -- fonte: legenda - Legenda completa da feição.
    ar_poli_km    numeric,           -- fonte: ar_poli_km - Área do polígono em km² segundo o IBGE.
    leg1_id       integer,           -- fonte: leg1_id - Código da legenda de primeiro nível.
    leg2_id       integer,           -- fonte: leg2_id - Código da legenda de segundo nível.
    geom              geometry(MultiPolygon, 4674),   -- fonte: shapefile (SIRGAS 2000). NULL se geom_anomala
    geom_anomala      boolean     NOT NULL DEFAULT false,
    geom_origem_texto text,
    edicao            text        NOT NULL,                       -- derivado: edicao do BDiA (ano da pasta versao_AAAA) em que esta versao entrou
    id_fonte          smallint    NOT NULL REFERENCES dim.fontes (id_fonte),
    importado_em      date        NOT NULL DEFAULT current_date,
    vigente_desde     date        NOT NULL DEFAULT current_date,
    vigente_ate       date,
    coletado_em       timestamptz NOT NULL DEFAULT now(),
    reaberto_em       date
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_ibge_vegetacao_vigente ON vetorial.ibge_vegetacao (id1) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_ibge_vegetacao_geom ON vetorial.ibge_vegetacao USING gist (geom) WHERE vigente_ate IS NULL;

COMMENT ON TABLE vetorial.ibge_vegetacao IS
    'Vegetação do BDiA (IBGE), 1:250.000. Espelho versionado, uma edicao por pasta versao_AAAA do IBGE. Ver ibge/vegetacao/LEIAME_vegetacao.md.';
COMMENT ON COLUMN vetorial.ibge_vegetacao.id1 IS 'Origem: id1. ID da feicao no shapefile do IBGE (chave; unico dentro da edicao).';
COMMENT ON COLUMN vetorial.ibge_vegetacao.edicao IS 'Edicao do BDiA (ano da pasta versao_AAAA) em que esta versao entrou.';

INSERT INTO catalogo.mapa_colunas (tabela, coluna, origem, fonte, observacao)
SELECT 'vetorial.ibge_vegetacao', c.column_name,
       CASE WHEN c.column_name = 'edicao' THEN 'derivado'
            WHEN c.column_name IN ('id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala','geom_origem_texto') THEN 'controle'
            WHEN c.column_name = 'geom' THEN 'geometria' ELSE c.column_name END,
       CASE WHEN c.column_name IN ('edicao','id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala') THEN 'pipeline' ELSE 'IBGE' END,
       NULL
FROM information_schema.columns c
WHERE c.table_schema = 'vetorial' AND c.table_name = 'ibge_vegetacao'
ON CONFLICT (tabela, coluna) DO UPDATE SET origem = EXCLUDED.origem, fonte = EXCLUDED.fonte;

GRANT SELECT, INSERT, UPDATE, DELETE ON vetorial.ibge_vegetacao TO etl;      -- DELETE: so para a rotina de retencao
GRANT SELECT ON vetorial.ibge_vegetacao TO leitura, geoserver, analistas;
GRANT MAINTAIN ON vetorial.ibge_vegetacao TO etl;

SELECT 'vetorial.ibge_vegetacao' AS item, count(*)::text AS valor FROM vetorial.ibge_vegetacao;
