-- Camada generica do SIDRA (IBGE): uma tabela de valores para todas as tabelas do SIDRA + dimensoes que dizem o que cada id significa.
-- Desenho aprovado em 2026-10-21 (ROADMAP.md, item 12). Valores em tabular, dimensoes em dim, o que foi coletado em catalogo.
-- Rodar como postgres:
--   .\infra\scripts\dw.ps1 psql -Arquivo ibge\sidra\sql\01_camada_generica.sql
-- Idempotente. So ASCII de proposito. Pre-requisitos: infra/postgres/etl_base.sql, dim.fontes com 'IBGE', dim.estados e dim.municipios.
--
-- Chaves: o que o SIDRA ja identifica de forma unica no mundo (tabela, classificacao, variavel, unidade) usa o codigo do SIDRA como id;
-- categoria tem id nosso (o codigo de categoria so e unico dentro da classificacao).

-- ---------------------------------------------------------------- dimensoes
CREATE TABLE IF NOT EXISTS dim.sidra_pesquisa (
    id_pesquisa smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      text NOT NULL UNIQUE,            -- slug nosso: censo_agropecuario, pam, lspa
    nome        text NOT NULL
);
COMMENT ON TABLE dim.sidra_pesquisa IS 'Pesquisas do IBGE que alimentam o SIDRA (Censo Agropecuario, PAM, LSPA...).';

CREATE TABLE IF NOT EXISTS dim.unidade (
    id_unidade integer PRIMARY KEY,              -- codigo da unidade no SIDRA (campo MC)
    nome       text NOT NULL,                    -- como o IBGE escreve (campo MN): Unidades, Hectares, Mil Reais...
    simbolo    text
);
COMMENT ON TABLE dim.unidade IS 'Unidades de medida do SIDRA (id = codigo MC do SIDRA).';

CREATE TABLE IF NOT EXISTS dim.sidra_situacao (
    id_situacao   smallint PRIMARY KEY,
    simbolo_sidra text NOT NULL UNIQUE,
    nome          text NOT NULL,
    descricao     text NOT NULL
);
COMMENT ON TABLE dim.sidra_situacao IS 'Simbolos que o SIDRA usa no lugar de um numero. valor NULL com id_situacao: o dado nao e um numero.';
INSERT INTO dim.sidra_situacao (id_situacao, simbolo_sidra, nome, descricao) VALUES
    (1, '-',   'zero',            'O fenomeno existe e o valor e zero.'),
    (2, 'X',   'sigilo',          'Valor inibido para nao identificar o informante (nao e zero; somas podem ficar abaixo do total).'),
    (3, '...', 'nao se aplica',   'O dado nao se aplica a este recorte.'),
    (4, '..',  'nao disponivel',  'O dado nao esta disponivel.')
ON CONFLICT (id_situacao) DO NOTHING;

CREATE TABLE IF NOT EXISTS dim.sidra_tabela (
    id_tabela      integer PRIMARY KEY,          -- numero da tabela no SIDRA (6956, 5457...)
    id_pesquisa    smallint NOT NULL REFERENCES dim.sidra_pesquisa (id_pesquisa),
    nome           text NOT NULL,
    periodicidade  text,                         -- anual, mensal, decenal...
    id_fonte       smallint NOT NULL REFERENCES dim.fontes (id_fonte),
    importado_em   date NOT NULL DEFAULT current_date
);
COMMENT ON TABLE dim.sidra_tabela IS 'Tabelas do SIDRA ja coletadas (id = numero oficial da tabela). So entram as pedidas.';

CREATE TABLE IF NOT EXISTS dim.sidra_classificacao (
    id_classificacao integer PRIMARY KEY,        -- codigo da classificacao no SIDRA (c227, c220...)
    nome             text NOT NULL
);
COMMENT ON TABLE dim.sidra_classificacao IS 'Classificacoes do SIDRA (eixos de cruzamento: produto, grupo de area, tipologia...).';

CREATE TABLE IF NOT EXISTS dim.sidra_tabela_eixo (
    id_tabela        integer  NOT NULL REFERENCES dim.sidra_tabela (id_tabela),
    posicao          smallint NOT NULL CHECK (posicao BETWEEN 1 AND 6),   -- 1 a 6 = id_cat1 a id_cat6 em tabular.sidra_valor
    id_classificacao integer  NOT NULL REFERENCES dim.sidra_classificacao (id_classificacao),
    PRIMARY KEY (id_tabela, posicao)
);
COMMENT ON TABLE dim.sidra_tabela_eixo IS 'Diz que classificacao cada id_catN de tabular.sidra_valor representa em cada tabela.';

CREATE TABLE IF NOT EXISTS dim.sidra_categoria (
    id_categoria     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_classificacao integer NOT NULL REFERENCES dim.sidra_classificacao (id_classificacao),
    codigo_sidra     integer NOT NULL,           -- codigo da categoria dentro da classificacao
    nome             text NOT NULL,
    id_unidade       integer REFERENCES dim.unidade (id_unidade),  -- quando a unidade depende da categoria
    limite_inferior  numeric,                    -- faixas (ex.: grupos de area em ha); NULL fora de faixas
    limite_superior  numeric,                    -- exclusivo; NULL = sem limite
    ordem            smallint,
    importado_em     date NOT NULL DEFAULT current_date,
    UNIQUE (id_classificacao, codigo_sidra)
);
COMMENT ON TABLE dim.sidra_categoria IS 'Categorias de cada classificacao (produtos, faixas de area...). id nosso; codigo_sidra e o codigo oficial.';

CREATE TABLE IF NOT EXISTS dim.sidra_variavel (
    id_variavel integer PRIMARY KEY,             -- codigo da variavel no SIDRA
    nome        text NOT NULL,
    id_unidade  integer REFERENCES dim.unidade (id_unidade)
);
COMMENT ON TABLE dim.sidra_variavel IS 'Variaveis do SIDRA (id = codigo oficial).';

-- ---------------------------------------------------------------- valores
CREATE SEQUENCE IF NOT EXISTS tabular.sidra_valor_id_seq;

-- Uma particao por tabela do SIDRA (LIST em id_tabela), criada por catalogo.sidra_garantir_particao.
-- Local: nivel 6 = municipio (id_municipio), 3 = UF (id_estado), 1 = Brasil (ambos NULL).
-- Sem linha = o IBGE informou zero ('-') ou nao se aplica ('...'), salvo tabelas configuradas para guardar os simbolos.
-- Versoes: vigente = vigente_ate IS NULL (mesma regra dos espelhos versionados do projeto; o IBGE revisa anos anteriores).
CREATE TABLE IF NOT EXISTS tabular.sidra_valor (
    id_tabela     integer  NOT NULL REFERENCES dim.sidra_tabela (id_tabela),
    id            bigint   NOT NULL DEFAULT nextval('tabular.sidra_valor_id_seq'),
    periodo       integer  NOT NULL,             -- ano (2017) ou ano e mes (202501), como o SIDRA
    nivel         smallint NOT NULL CHECK (nivel IN (1, 3, 6)),
    id_municipio  integer  REFERENCES dim.municipios (id_municipio),
    id_estado     smallint REFERENCES dim.estados (id_estado),
    id_variavel   integer  NOT NULL REFERENCES dim.sidra_variavel (id_variavel),
    id_cat1       integer  REFERENCES dim.sidra_categoria (id_categoria),
    id_cat2       integer  REFERENCES dim.sidra_categoria (id_categoria),
    id_cat3       integer  REFERENCES dim.sidra_categoria (id_categoria),
    id_cat4       integer  REFERENCES dim.sidra_categoria (id_categoria),
    id_cat5       integer  REFERENCES dim.sidra_categoria (id_categoria),
    id_cat6       integer  REFERENCES dim.sidra_categoria (id_categoria),
    valor         numeric,
    id_situacao   smallint REFERENCES dim.sidra_situacao (id_situacao),
    id_unidade    integer  REFERENCES dim.unidade (id_unidade),
    id_carga      bigint   NOT NULL REFERENCES catalogo.cargas (id),
    vigente_desde date     NOT NULL,
    vigente_ate   date,
    reaberto_em   date,
    PRIMARY KEY (id_tabela, id),
    CHECK ((nivel = 6) = (id_municipio IS NOT NULL)),
    CHECK ((nivel = 3) = (id_estado IS NOT NULL))
) PARTITION BY LIST (id_tabela);
COMMENT ON TABLE tabular.sidra_valor IS
    'Valores de tabelas do SIDRA (IBGE), uma particao por tabela. Ids em vez de texto: ver dim.sidra_*. id_catN = categoria da classificacao que dim.sidra_tabela_eixo indica na posicao N. Sem linha = zero ou nao se aplica.';
COMMENT ON COLUMN tabular.sidra_valor.valor IS 'NULL com id_situacao preenchida: o IBGE nao informou numero (ex.: X = sigilo).';

-- Chave natural da versao vigente (NULLs tratados como 0, pois os ids comecam em 1)
CREATE UNIQUE INDEX IF NOT EXISTS ux_sidra_valor_vigente ON tabular.sidra_valor
    (id_tabela, periodo, nivel, COALESCE(id_municipio, 0), COALESCE(id_estado, 0), id_variavel,
     COALESCE(id_cat1, 0), COALESCE(id_cat2, 0), COALESCE(id_cat3, 0), COALESCE(id_cat4, 0), COALESCE(id_cat5, 0), COALESCE(id_cat6, 0))
    WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_sidra_valor_municipio ON tabular.sidra_valor (id_municipio) WHERE id_municipio IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_sidra_valor_cat1 ON tabular.sidra_valor (id_tabela, id_cat1) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_sidra_valor_carga ON tabular.sidra_valor (id_carga);

-- ---------------------------------------------------------------- o que foi coletado
CREATE TABLE IF NOT EXISTS catalogo.sidra_recorte (
    id_recorte     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tabela      integer  NOT NULL REFERENCES dim.sidra_tabela (id_tabela),
    nivel          smallint NOT NULL,
    periodo_inicio integer,
    periodo_fim    integer,
    filtros        jsonb    NOT NULL,            -- classificacao -> categorias pedidas; variaveis
    linhas_lidas   bigint,
    linhas_gravadas bigint,
    coletado_em    timestamptz NOT NULL DEFAULT now(),
    id_carga       bigint REFERENCES catalogo.cargas (id)
);
COMMENT ON TABLE catalogo.sidra_recorte IS 'O que exatamente foi carregado de cada tabela do SIDRA (a coleta e sempre sob demanda, por recorte).';
CREATE INDEX IF NOT EXISTS ix_sidra_recorte_tabela ON catalogo.sidra_recorte (id_tabela);

-- ---------------------------------------------------------------- particao por tabela (o etl nao tem DDL)
CREATE OR REPLACE FUNCTION catalogo.sidra_garantir_particao(p_id_tabela integer) RETURNS text
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE nome text := format('sidra_valor_t%s', p_id_tabela);
BEGIN
    IF p_id_tabela IS NULL OR p_id_tabela <= 0 THEN
        RAISE EXCEPTION 'id_tabela invalido: %', p_id_tabela;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM dim.sidra_tabela WHERE id_tabela = p_id_tabela) THEN
        RAISE EXCEPTION 'a tabela % nao esta em dim.sidra_tabela; cadastre antes de criar a particao', p_id_tabela;
    END IF;
    EXECUTE format('CREATE TABLE IF NOT EXISTS tabular.%I PARTITION OF tabular.sidra_valor FOR VALUES IN (%s)', nome, p_id_tabela);
    RETURN format('tabular.%I', nome);
END $$;

REVOKE ALL ON FUNCTION catalogo.sidra_garantir_particao(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION catalogo.sidra_garantir_particao(integer) TO etl;

-- ---------------------------------------------------------------- permissoes do etl (so DML; a particao nova herda do pai)
GRANT SELECT, INSERT, UPDATE ON dim.sidra_pesquisa, dim.unidade, dim.sidra_tabela, dim.sidra_classificacao, dim.sidra_tabela_eixo,
    dim.sidra_categoria, dim.sidra_variavel, catalogo.sidra_recorte TO etl;
GRANT SELECT, INSERT, UPDATE ON tabular.sidra_valor TO etl;            -- DELETE so pela retencao (infra/postgres/retencao.sql)
GRANT USAGE ON SEQUENCE tabular.sidra_valor_id_seq TO etl;
GRANT MAINTAIN ON dim.sidra_pesquisa, dim.unidade, dim.sidra_situacao, dim.sidra_tabela, dim.sidra_classificacao, dim.sidra_tabela_eixo,
    dim.sidra_categoria, dim.sidra_variavel, catalogo.sidra_recorte, tabular.sidra_valor TO etl;

