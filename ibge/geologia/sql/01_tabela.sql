-- Geologia (BDiA, IBGE, 1:250.000) como ESPELHO VERSIONADO: vetorial.ibge_geologia. Idempotente.
-- Rodar como postgres (o etl so tem DML):
--   .\infra\scripts\dw.ps1 psql -Arquivo ibge\geologia\sql\01_tabela.sql
--
-- Mapa geológico do Brasil (litoestratigrafia) do BDiA, 1:250.000: uma feição por unidade geológica mapeada. Colunas com os nomes do shapefile em minusculas; os campos que o IBGE grava como numero
-- decimal mas sao codigos inteiros viram integer. Chave: id1 (id da feicao no shapefile). Mesmas regras das outras fontes: vigente = vigente_ate IS NULL; nada e apagado na coleta.

INSERT INTO dim.fontes (nome, sigla, url, descricao)
SELECT 'IBGE', 'IBGE', 'https://www.ibge.gov.br', 'Instituto Brasileiro de Geografia e Estatistica'
WHERE NOT EXISTS (SELECT 1 FROM dim.fontes WHERE nome = 'IBGE');

CREATE TABLE IF NOT EXISTS vetorial.ibge_geologia (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id1           bigint NOT NULL,   -- fonte: id1 - ID da feição no shapefile do IBGE (a chave; único dentro da edição).
    ordem         integer,           -- fonte: ordem - Número de ordem da unidade na legenda.
    cd_fcim       text,              -- fonte: cd_fcim - Código da folha da Carta Internacional do Mundo ao Milionésimo (CIM) em que a feição está.
    leg_carga     text,              -- fonte: leg_carga - Código da unidade na legenda da carga original.
    id_unidade    integer,           -- fonte: id_unidade - Identificador da unidade geológica.
    nm_unidade    text,              -- fonte: nm_unidade - Nome da unidade geológica.
    letra_simb    text,              -- fonte: letra_simb - Sigla (letra-símbolo) da unidade.
    nm_lito1      text,              -- fonte: nm_lito1 - Litotipo 1 (rocha predominante da unidade).
    nm_lito2      text,              -- fonte: nm_lito2 - Litotipo 2.
    nm_lito3      text,              -- fonte: nm_lito3 - Litotipo 3.
    nm_lito4      text,              -- fonte: nm_lito4 - Litotipo 4.
    ar_poli_km    numeric,           -- fonte: ar_poli_km - Área do polígono em km² segundo o IBGE.
    nm_tempo_g    text,              -- fonte: nm_tempo_g - Tempo geológico (era e período) da unidade.
    nm_provinc    text,              -- fonte: nm_provinc - Província geológica.
    nm_sub_pro    text,              -- fonte: nm_sub_pro - Subprovíncia geológica.
    cd_prov_id    integer,           -- fonte: cd_prov_id - Código da província geológica.
    cd_sub_pro    integer,           -- fonte: cd_sub_pro - Código da subprovíncia geológica.
    nm_tp_roc     text,              -- fonte: nm_tp_roc - Tipo de rocha (sedimentar, ígnea, metamórfica...).
    nm_stp_roc    text,              -- fonte: nm_stp_roc - Subtipo de rocha (ex.: sedimentar clástica).
    geom              geometry(MultiPolygon, 4674),   -- fonte: shapefile (SIRGAS 2000). NULL se geom_anomala
    geom_anomala      boolean     NOT NULL DEFAULT false,
    geom_origem_texto text,
    edicao            text        NOT NULL,                       -- derivado: edicao do BDiA (ano da pasta versao_AAAA) em que esta versao entrou
    id_fonte          smallint    NOT NULL REFERENCES dim.fontes (id_fonte),
    importado_em      date        NOT NULL DEFAULT current_date,
    vigente_desde     date        NOT NULL DEFAULT current_date,
    vigente_ate       date,
    coletado_em       timestamptz NOT NULL DEFAULT now(),
    reaberto_em       date
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_ibge_geologia_vigente ON vetorial.ibge_geologia (id1) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_ibge_geologia_geom ON vetorial.ibge_geologia USING gist (geom) WHERE vigente_ate IS NULL;

COMMENT ON TABLE vetorial.ibge_geologia IS
    'Geologia do BDiA (IBGE), 1:250.000. Espelho versionado, uma edicao por pasta versao_AAAA do IBGE. Ver ibge/geologia/LEIAME_geologia.md.';
COMMENT ON COLUMN vetorial.ibge_geologia.id1 IS 'Origem: id1. ID da feicao no shapefile do IBGE (chave; unico dentro da edicao).';
COMMENT ON COLUMN vetorial.ibge_geologia.edicao IS 'Edicao do BDiA (ano da pasta versao_AAAA) em que esta versao entrou.';

INSERT INTO catalogo.mapa_colunas (tabela, coluna, origem, fonte, observacao)
SELECT 'vetorial.ibge_geologia', c.column_name,
       CASE WHEN c.column_name = 'edicao' THEN 'derivado'
            WHEN c.column_name IN ('id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala','geom_origem_texto') THEN 'controle'
            WHEN c.column_name = 'geom' THEN 'geometria' ELSE c.column_name END,
       CASE WHEN c.column_name IN ('edicao','id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala') THEN 'pipeline' ELSE 'IBGE' END,
       NULL
FROM information_schema.columns c
WHERE c.table_schema = 'vetorial' AND c.table_name = 'ibge_geologia'
ON CONFLICT (tabela, coluna) DO UPDATE SET origem = EXCLUDED.origem, fonte = EXCLUDED.fonte;

GRANT SELECT, INSERT, UPDATE, DELETE ON vetorial.ibge_geologia TO etl;      -- DELETE: so para a rotina de retencao
GRANT SELECT ON vetorial.ibge_geologia TO leitura, geoserver, analistas;
GRANT MAINTAIN ON vetorial.ibge_geologia TO etl;

SELECT 'vetorial.ibge_geologia' AS item, count(*)::text AS valor FROM vetorial.ibge_geologia;
