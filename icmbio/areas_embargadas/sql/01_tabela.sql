-- Areas embargadas do ICMBio como ESPELHO VERSIONADO: vetorial.icmbio_areas_embargadas. Idempotente.
-- Rodar como postgres (o etl so tem DML):
--   .\infra\scripts\dw.ps1 psql -Arquivo icmbio\areas_embargadas\sql\01_tabela.sql
--
-- Uma linha por POLIGONO da camada publica do ICMBio. Um embargo (numero_emb) pode ter varios poligonos (ate 68 iguais nos demais campos), e a camada nao tem
-- id unico: a chave (chave_linha) e a identidade do registro (numero_emb, serie, numero_ai, documento, UC, municipio, UF, data, processo) + ordinal para os
-- poligonos identicos. Colunas com os nomes da fonte em minusculas; texto sempre `text` (a fonte usa ' ' no lugar de vazio: vira NULL).
-- DADO PESSOAL (mesma decisao do IBAMA): nome do autuado entra como a fonte publica; CPF de pessoa fisica NAO e guardado, so o HMAC-SHA256 (dwlib/documento.py,
-- a mesma chave do IBAMA); CNPJ e texto livre entram como vem. NAO publicar esta tabela no GeoServer sem tirar `autuado`.

INSERT INTO dim.fontes (nome, sigla, url, descricao)
SELECT 'ICMBio', 'ICMBio', 'https://www.gov.br/icmbio', 'Instituto Chico Mendes de Conservacao da Biodiversidade (areas embargadas)'
WHERE NOT EXISTS (SELECT 1 FROM dim.fontes WHERE nome = 'ICMBio');

CREATE TABLE IF NOT EXISTS vetorial.icmbio_areas_embargadas (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave_linha       text        NOT NULL,         -- derivado: identidade do poligono (a fonte nao tem id unico); ver LEIAME
    objectid          bigint,                       -- fonte: OBJECTID da camada (nao e estavel entre republicacoes: nao entra na comparacao)
    vw_num_emb        numeric,                      -- fonte: vw_num_emb (sequencial da visao de origem; nao entra na comparacao)
    numero_emb        text,                         -- fonte: numero_emb (numero do termo de embargo; repete entre poligonos do mesmo embargo)
    serie             text,                         -- fonte: serie (A, B ou vazio)
    origem            text,                         -- fonte: origem (Eletronico ou Papel)
    numero_ai         text,                         -- fonte: numero_ai (numero do auto de infracao)
    cpf_cnpj          text,                         -- fonte: cpf_cnpj. CPF de pessoa fisica NAO e guardado (NULL); CNPJ e texto livre entram como vem
    tipo_doc_autuado  text,                         -- derivado: CPF, CNPJ, OUTRO ou NULL (sem documento)
    doc_valido        boolean,                      -- derivado: digitos verificadores do CPF/CNPJ conferem (false = provavel erro de digitacao na fonte)
    cpf_autuado_hash  text,                         -- derivado: HMAC-SHA256 dos 11 digitos do CPF (so se tipo_doc_autuado = CPF); mesma chave do IBAMA
    autuado           text,                         -- fonte: autuado (nome do autuado; dado pessoal como a fonte publica)
    desc_infra        text,                         -- fonte: desc_infra
    desc_sanc         text,                         -- fonte: desc_sanc
    artigo_1          text,                         -- fonte: artigo_1
    artigo_2          text,                         -- fonte: artigo_2
    tipo_infra        text,                         -- fonte: tipo_infra
    nome_uc           text,                         -- fonte: nome_uc (unidade de conservacao do embargo)
    cnuc              text,                         -- fonte: cnuc (codigo da UC no CNUC)
    municipio         text,                         -- fonte: municipio
    uf                text,                         -- fonte: uf
    id_estado         smallint    REFERENCES dim.estados (id_estado),   -- derivado de uf
    data              text,                         -- fonte: data (AAAA-MM-DD; 'None' em 5 linhas)
    data_embargo      date,                         -- derivado: data como date
    ano               text,                         -- fonte: ano
    obs               text,                         -- fonte: obs
    julgamento        text,                         -- fonte: julgamento
    area              text,                         -- fonte: area (TEXTO livre: '2,55ha', '300 m2', 'Nao informada', 'Tamanho total das areas embargadas: 1,33ha')
    area_informada_ha numeric,                      -- derivado: area em hectares so quando o texto e um numero com ha/hectare(s)/m2; senao NULL. NAO e a area do poligono
    processo          text,                         -- fonte: processo
    ngi               text,                         -- fonte: ngi
    ct                text,                         -- fonte: ct
    gr                text,                         -- fonte: gr
    gr_nome           text,                         -- fonte: gr_nome
    geom              geometry(MultiPolygon, 4674), -- fonte: geometria da camada (SIRGAS 2000). NULL se geom_anomala
    geom_anomala      boolean     NOT NULL DEFAULT false,
    geom_origem_texto text,
    id_fonte          smallint    NOT NULL REFERENCES dim.fontes (id_fonte),
    importado_em      date        NOT NULL DEFAULT current_date,
    vigente_desde     date        NOT NULL DEFAULT current_date,
    vigente_ate       date,
    coletado_em       timestamptz NOT NULL DEFAULT now(),
    reaberto_em       date
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_icmbio_embargos_vigente ON vetorial.icmbio_areas_embargadas (chave_linha) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_icmbio_embargos_geom ON vetorial.icmbio_areas_embargadas USING gist (geom) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_icmbio_embargos_hash ON vetorial.icmbio_areas_embargadas (cpf_autuado_hash) WHERE vigente_ate IS NULL AND cpf_autuado_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_icmbio_embargos_cnpj ON vetorial.icmbio_areas_embargadas (cpf_cnpj) WHERE vigente_ate IS NULL AND cpf_cnpj IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_icmbio_embargos_num  ON vetorial.icmbio_areas_embargadas (numero_emb) WHERE vigente_ate IS NULL;

COMMENT ON TABLE vetorial.icmbio_areas_embargadas IS
    'Areas embargadas do ICMBio (camada publica do ArcGIS Online do ICMBio). Espelho versionado, uma linha por poligono. Dado pessoal: CPF so como HMAC, nome do autuado como a fonte publica; nao publicar no GeoServer sem tirar autuado. Ver icmbio/areas_embargadas/LEIAME_areas_embargadas.md.';
COMMENT ON COLUMN vetorial.icmbio_areas_embargadas.chave_linha IS 'Derivado: a camada nao tem id unico; identidade = numero_emb|serie|numero_ai|documento|nome_uc|municipio|uf|data|processo (+ ordinal se identicos).';
COMMENT ON COLUMN vetorial.icmbio_areas_embargadas.cpf_cnpj IS 'Origem: cpf_cnpj. CPF de pessoa fisica nao e guardado (NULL; ver cpf_autuado_hash).';
COMMENT ON COLUMN vetorial.icmbio_areas_embargadas.area IS 'Origem: area. Texto livre da fonte; nao e a area do poligono.';

INSERT INTO catalogo.mapa_colunas (tabela, coluna, origem, fonte, observacao)
SELECT 'vetorial.icmbio_areas_embargadas', c.column_name,
       CASE WHEN c.column_name IN ('chave_linha','tipo_doc_autuado','doc_valido','cpf_autuado_hash','id_estado','data_embargo','area_informada_ha') THEN 'derivado'
            WHEN c.column_name IN ('id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala','geom_origem_texto') THEN 'controle'
            WHEN c.column_name = 'geom' THEN 'geometria' WHEN c.column_name = 'objectid' THEN 'OBJECTID' ELSE c.column_name END,
       CASE WHEN c.column_name IN ('chave_linha','tipo_doc_autuado','doc_valido','cpf_autuado_hash','id_estado','data_embargo','area_informada_ha','id','id_fonte','importado_em','vigente_desde',
                                   'vigente_ate','coletado_em','reaberto_em','geom_anomala') THEN 'pipeline' ELSE 'ICMBio' END,
       CASE WHEN c.column_name = 'id_estado' THEN 'dim.estados' WHEN c.column_name = 'cpf_autuado_hash' THEN 'HMAC-SHA256 com a mesma chave do IBAMA' END
FROM information_schema.columns c
WHERE c.table_schema = 'vetorial' AND c.table_name = 'icmbio_areas_embargadas'
ON CONFLICT (tabela, coluna) DO UPDATE SET origem = EXCLUDED.origem, fonte = EXCLUDED.fonte;

GRANT SELECT, INSERT, UPDATE, DELETE ON vetorial.icmbio_areas_embargadas TO etl;      -- DELETE: so para a rotina de retencao
GRANT SELECT ON vetorial.icmbio_areas_embargadas TO leitura, geoserver, analistas;
GRANT MAINTAIN ON vetorial.icmbio_areas_embargadas TO etl;

SELECT 'vetorial.icmbio_areas_embargadas' AS item, count(*)::text AS valor FROM vetorial.icmbio_areas_embargadas;
