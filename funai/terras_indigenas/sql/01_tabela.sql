-- Terras indigenas da FUNAI (camada Funai:tis_poligonais do servidor de mapas da FUNAI) como ESPELHO VERSIONADO:
-- vetorial.funai_terras_indigenas. Idempotente. Rodar como postgres (o etl so tem DML):
--   .\infra\scripts\dw.ps1 psql -Arquivo funai\terras_indigenas\sql\01_tabela.sql
--
-- Regras (as mesmas do SICAR, do PRODES e do MapBiomas Alerta): a tabela espelha o que o servidor publica hoje; cada terra (terrai_codigo)
-- tem versoes (vigente_desde/vigente_ate); terra que o servidor deixa de publicar tem a versao FECHADA (nada e apagado na coleta); terra que
-- some e volta IDENTICA tem a versao reaberta. Colunas com os nomes da fonte; texto sempre `text`. So ~665 linhas: os indices ja nascem aqui.

INSERT INTO dim.fontes (nome, sigla, url, descricao)
SELECT 'FUNAI', 'FUNAI', 'https://www.gov.br/funai', 'Fundacao Nacional dos Povos Indigenas - terras indigenas (poligonais)'
WHERE NOT EXISTS (SELECT 1 FROM dim.fontes WHERE nome = 'FUNAI');

CREATE TABLE IF NOT EXISTS vetorial.funai_terras_indigenas (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terrai_codigo            integer     NOT NULL,          -- fonte: terrai_codigo (chave estavel da terra indigena)
    terrai_nome              text,                          -- fonte: terrai_nome
    etnia_nome               text,                          -- fonte: etnia_nome (pode listar mais de uma etnia)
    municipio_nome           text,                          -- fonte: municipio_nome (pode listar mais de um municipio)
    uf_sigla                 text,                          -- fonte: uf_sigla (pode listar mais de uma UF)
    id_estado                smallint REFERENCES dim.estados (id_estado),   -- derivado de uf_sigla SO quando e uma UF unica
    superficie_perimetro_ha  numeric,                       -- fonte: superficie_perimetro_ha (hectares)
    fase_ti                  text,                          -- fonte: fase_ti (Regularizada, Declarada, Delimitada, Homologada, Encaminhada RI, Em Estudo)
    modalidade_ti            text,                          -- fonte: modalidade_ti (Tradicionalmente ocupada, Reserva Indigena, Dominial...)
    reestudo_ti              text,                          -- fonte: reestudo_ti
    cr                       text,                          -- fonte: cr (Coordenacao Regional)
    faixa_fronteira          text,                          -- fonte: faixa_fronteira (Sim/Nao como a fonte escreve)
    undadm_codigo            bigint,                        -- fonte: undadm_codigo (unidade administrativa)
    undadm_nome              text,                          -- fonte: undadm_nome
    undadm_sigla             text,                          -- fonte: undadm_sigla
    dominio_uniao            boolean,                       -- fonte: dominio_uniao (t/f)
    data_atualizacao         date,                          -- fonte: data_atualizacao (dd/mm/aaaa na origem)
    geom                     geometry(MultiPolygon, 4674),  -- fonte: geometria (SIRGAS 2000). NULL quando geom_anomala
    geom_anomala             boolean     NOT NULL DEFAULT false,
    geom_origem_texto        text,
    id_fonte                 smallint    NOT NULL REFERENCES dim.fontes (id_fonte),
    importado_em             date        NOT NULL DEFAULT current_date,
    vigente_desde            date        NOT NULL DEFAULT current_date,
    vigente_ate              date,
    coletado_em              timestamptz NOT NULL DEFAULT now(),
    reaberto_em              date
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_funai_ti_vigente ON vetorial.funai_terras_indigenas (terrai_codigo) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_funai_ti_geom ON vetorial.funai_terras_indigenas USING gist (geom) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_funai_ti_estado ON vetorial.funai_terras_indigenas (id_estado) WHERE vigente_ate IS NULL;

COMMENT ON TABLE vetorial.funai_terras_indigenas IS
    'Terras indigenas (poligonais) da FUNAI, camada Funai:tis_poligonais do servidor de mapas da FUNAI. Espelho versionado: vigente = vigente_ate IS NULL. Ver funai/terras_indigenas/LEIAME_terras_indigenas.md.';
COMMENT ON COLUMN vetorial.funai_terras_indigenas.terrai_codigo IS 'Origem: terrai_codigo. Chave estavel; uma versao vigente por terra indigena.';
COMMENT ON COLUMN vetorial.funai_terras_indigenas.id_estado IS 'Derivado de uf_sigla so quando a terra esta numa UF unica; NULL quando a fonte lista mais de uma UF.';
COMMENT ON COLUMN vetorial.funai_terras_indigenas.fase_ti IS 'Origem: fase_ti (fase do processo de regularizacao fundiaria).';

