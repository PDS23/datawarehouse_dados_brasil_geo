-- Rodar como postgres (o etl so tem DML):
--   .\infra\scripts\dw.ps1 psql -Arquivo mma\areas_prioritarias\sql\01_tabela.sql
--
-- Os 7 shapefiles do MMA (um por bioma/regiao) tem esquemas diferentes. Uma tabela so: as colunas comuns harmonizadas (camada_origem diz de qual arquivo veio) e TUDO o que a fonte
-- publica em atributos_originais (jsonb). Chave: (camada_origem, cod_area). Edicao estatica ("2a atualizacao", 2022); o espelho versionado detecta uma edicao nova.

INSERT INTO dim.fontes (nome, sigla, url, descricao)
SELECT 'MMA', 'MMA', 'https://dados.mma.gov.br', 'Ministerio do Meio Ambiente e Mudanca do Clima - dados abertos'
WHERE NOT EXISTS (SELECT 1 FROM dim.fontes WHERE nome = 'MMA');

CREATE TABLE IF NOT EXISTS vetorial.mma_areas_prioritarias (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camada_origem          text        NOT NULL,         -- derivado: arquivo de origem (amazonia, caatinga, cerrado_pantanal, mata_atlantica, pampa, zona_costeira_marinha, areas_hibridas)
    cod_area               text        NOT NULL,         -- fonte: COD_area (ID_AP na zona costeira e marinha); unico dentro da camada
    nome_area              text,                         -- fonte: Nome_area / NOME / Nome_AP / NOME_AP (so algumas camadas)
    importancia_biologica  text,                         -- fonte: Import_bio / ImportBio_ / IMP / IB_pos (extremamente alta, muito alta, alta...)
    prioridade_acao        text,                         -- fonte: Prior_acao / Prioridade / PRIO / PA_pos
    acao_principal_codigo  text,                         -- fonte: codigo da acao principal (Acao_princ, AcaoPriori, AcaoPrinci, AcPrinc); o texto esta na lista de acoes do MMA (nao carregada)
    acao_principal         text,                         -- fonte: texto da acao principal, quando a camada o traz
    acoes_complementares   text,                         -- fonte: demais acoes, separadas por " | " (Acao_2/3, Acao2/3/4, Ac2/Ac3 conforme a camada)
    estados                text,                         -- fonte: Estados (so cerrado_pantanal)
    area_ha                numeric,                      -- fonte: Area_ha
    atributos_originais    jsonb       NOT NULL,         -- fonte: todos os campos do shapefile como publicados (menos OBJECTID e Shape_*, artefatos do ArcGIS)
    geom                   geometry(MultiPolygon, 4674), -- fonte: shapefile (SIRGAS 2000; o Z e descartado)
    geom_anomala           boolean     NOT NULL DEFAULT false,
    geom_origem_texto      text,
    edicao                 text        NOT NULL,         -- derivado: edicao do MMA (do nome do arquivo, ex.: '2a atualizacao')
    id_fonte               smallint    NOT NULL REFERENCES dim.fontes (id_fonte),
    importado_em           date        NOT NULL DEFAULT current_date,
    vigente_desde          date        NOT NULL DEFAULT current_date,
    vigente_ate            date,
    coletado_em            timestamptz NOT NULL DEFAULT now(),
    reaberto_em            date
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_mma_ap_vigente ON vetorial.mma_areas_prioritarias (camada_origem, cod_area) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_mma_ap_geom ON vetorial.mma_areas_prioritarias USING gist (geom) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_mma_ap_prioridade ON vetorial.mma_areas_prioritarias (prioridade_acao) WHERE vigente_ate IS NULL;

COMMENT ON TABLE vetorial.mma_areas_prioritarias IS
    'Areas Prioritarias para a Conservacao da Biodiversidade (MMA), 2a atualizacao (2022): 7 shapefiles com esquemas diferentes numa tabela, colunas comuns harmonizadas e atributos_originais com tudo. Ver mma/areas_prioritarias/LEIAME_areas_prioritarias.md.';
COMMENT ON COLUMN vetorial.mma_areas_prioritarias.camada_origem IS 'Derivado: arquivo do MMA de onde a area veio. A chave e (camada_origem, cod_area).';
COMMENT ON COLUMN vetorial.mma_areas_prioritarias.atributos_originais IS 'Todos os campos do shapefile como publicados (jsonb), menos OBJECTID e Shape_*.';

INSERT INTO catalogo.mapa_colunas (tabela, coluna, origem, fonte, observacao)
SELECT 'vetorial.mma_areas_prioritarias', c.column_name,
       CASE WHEN c.column_name IN ('camada_origem','edicao') THEN 'derivado'
            WHEN c.column_name IN ('id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala','geom_origem_texto') THEN 'controle'
            WHEN c.column_name = 'geom' THEN 'geometria' WHEN c.column_name = 'atributos_originais' THEN 'todos os campos do shapefile' ELSE 'varia por camada (ver LEIAME)' END,
       CASE WHEN c.column_name IN ('camada_origem','edicao','id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala') THEN 'pipeline' ELSE 'MMA' END,
       NULL
FROM information_schema.columns c
WHERE c.table_schema = 'vetorial' AND c.table_name = 'mma_areas_prioritarias'
ON CONFLICT (tabela, coluna) DO UPDATE SET origem = EXCLUDED.origem, fonte = EXCLUDED.fonte;

GRANT SELECT, INSERT, UPDATE, DELETE ON vetorial.mma_areas_prioritarias TO etl;      -- DELETE: so para a rotina de retencao
GRANT SELECT ON vetorial.mma_areas_prioritarias TO leitura, geoserver, analistas;
GRANT MAINTAIN ON vetorial.mma_areas_prioritarias TO etl;

