-- Unidades de conservacao (CNUC, Ministerio do Meio Ambiente) como ESPELHO VERSIONADO: vetorial.mma_unidades_conservacao. Idempotente.
-- Rodar como postgres (o etl so tem DML):
--   .\infra\scripts\dw.ps1 psql -Arquivo mma\unidades_conservacao\sql\01_tabela.sql
--
-- Regras (as mesmas das outras fontes vivas): a tabela espelha a ULTIMA EDICAO carregada; cada UC (cd_cnuc) tem versoes (vigente_desde/vigente_ate);
-- UC que a edicao nova nao traz tem a versao FECHADA (nada e apagado na coleta); UC que some e volta identica tem a versao reaberta.
-- O zip do CNUC tem dois shapefiles com UCs DIFERENTES: poligonos (geom) e pontos esquematicos de UCs sem poligono (geom_ponto). Colunas com os
-- nomes da fonte em minusculas; texto sempre `text`.
-- CARGA MANUAL AUTORIZADA (2026-10-27): o shapefile mais recente so existe em links do SharePoint do MMA; ver LEIAME_unidades_conservacao.md.

INSERT INTO dim.fontes (nome, sigla, url, descricao)
SELECT 'MMA', 'MMA', 'https://dados.mma.gov.br', 'Ministerio do Meio Ambiente e Mudanca do Clima - dados abertos (CNUC: unidades de conservacao)'
WHERE NOT EXISTS (SELECT 1 FROM dim.fontes WHERE nome = 'MMA');

CREATE TABLE IF NOT EXISTS vetorial.mma_unidades_conservacao (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cd_cnuc           text        NOT NULL,         -- fonte: cd_cnuc (codigo da UC no CNUC; chave estavel, unica em cada shapefile)
    camada_origem     text        NOT NULL,         -- derivado: 'poligonos' ou 'pontos' (shapefile do zip de onde a UC veio)
    docleg_id         text,                         -- fonte: docleg_id (so poligonos)
    uc_id             text,                         -- fonte: uc_id (so poligonos)
    wdpa_pid          text,                         -- fonte: wdpa_pid (codigo da UC no World Database on Protected Areas)
    nome_uc           text,                         -- fonte: nome_uc
    nome_abrev        text,                         -- fonte: NomeAbrev (so pontos)
    cria_ano          text,                         -- fonte: cria_ano (poligonos: dd-mm-aaaa; pontos: so o ano)
    ano_criacao       smallint,                     -- derivado: ano de cria_ano
    cria_ato          text,                         -- fonte: cria_ato (ato legal de criacao)
    outro_ato         text,                         -- fonte: outro_ato (so poligonos)
    pl_manejo         text,                         -- fonte: pl_manejo (tem plano de manejo? Sim/Nao; so poligonos)
    co_gestor         text,                         -- fonte: co_gestor (tem conselho gestor? so poligonos)
    quali_pol         text,                         -- fonte: quali_pol (qualidade do poligono: memorial descritivo, estimativa, esquematico)
    ppgr              text,                         -- fonte: ppgr (programa/projeto de gestao relacionado; so poligonos)
    ppgr_rev          text,                         -- fonte: ppgr_rev (so pontos)
    ha_total          numeric,                      -- fonte: ha_total (hectares do poligono; so poligonos)
    ha_ato            numeric,                      -- fonte: ha_ato (hectares segundo o ato de criacao; so poligonos)
    esfera            text,                         -- fonte: esfera (Federal, Estadual, Municipal; a capitalizacao varia entre as camadas: use lower())
    uf                text,                         -- fonte: uf (nomes por extenso; lista separada por virgula se a UC cruza UFs)
    municipio         text,                         -- fonte: municipio (lista "NOME (UF), NOME (UF)"; so poligonos)
    org_gestor        text,                         -- fonte: org_gestor
    grupo             text,                         -- fonte: grupo (poligonos: Protecao Integral / Uso Sustentavel; pontos: PI / US)
    categoria         text,                         -- fonte: categoria
    cat_iucn          text,                         -- fonte: cat_iucn (so poligonos)
    amazonia          numeric,                      -- fonte: amazonia (ha da UC no bioma; so poligonos)
    caatinga          numeric,                      -- fonte: caatinga (ha)
    cerrado           numeric,                      -- fonte: cerrado (ha)
    matlantica        numeric,                      -- fonte: matlantica (ha, Mata Atlantica)
    pampa             numeric,                      -- fonte: pampa (ha)
    pantanal          numeric,                      -- fonte: pantanal (ha)
    marinho           numeric,                      -- fonte: marinho (ha)
    situacao          text,                         -- fonte: situacao (so poligonos; hoje sempre Ativo)
    limite            text,                         -- fonte: limite (so poligonos)
    sitiopatri        text,                         -- fonte: sitiopatri (sitio do patrimonio mundial; so pontos)
    ramsar            text,                         -- fonte: ramsar (so pontos)
    mosaico           text,                         -- fonte: mosaico (so pontos)
    biosfera          text,                         -- fonte: biosfera (reserva da biosfera; so pontos)
    siscosmar         integer,                      -- fonte: SisCosMar (so pontos)
    longitude_ponto   double precision,             -- fonte: geometria do shapefile de pontos (so pontos)
    latitude_ponto    double precision,
    geom_ponto        geometry(Point, 4674) GENERATED ALWAYS AS (
                          CASE WHEN longitude_ponto IS NOT NULL AND latitude_ponto IS NOT NULL
                               THEN ST_SetSRID(ST_MakePoint(longitude_ponto, latitude_ponto), 4674) END) STORED,   -- derivado: ponto esquematico das UCs sem poligono
    geom              geometry(MultiPolygon, 4674), -- fonte: geometria do shapefile de poligonos (SIRGAS 2000). NULL nas UCs so de ponto ou se geom_anomala
    geom_anomala      boolean     NOT NULL DEFAULT false,
    geom_origem_texto text,
    edicao            text        NOT NULL,         -- derivado: edicao do CNUC (AAAA_MM, do nome do zip) em que esta versao entrou
    id_fonte          smallint    NOT NULL REFERENCES dim.fontes (id_fonte),
    importado_em      date        NOT NULL DEFAULT current_date,
    vigente_desde     date        NOT NULL DEFAULT current_date,
    vigente_ate       date,
    coletado_em       timestamptz NOT NULL DEFAULT now(),
    reaberto_em       date
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_mma_uc_vigente ON vetorial.mma_unidades_conservacao (cd_cnuc) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_mma_uc_geom       ON vetorial.mma_unidades_conservacao USING gist (geom)       WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_mma_uc_geom_ponto ON vetorial.mma_unidades_conservacao USING gist (geom_ponto) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_mma_uc_categoria  ON vetorial.mma_unidades_conservacao (categoria)            WHERE vigente_ate IS NULL;

COMMENT ON TABLE vetorial.mma_unidades_conservacao IS
    'Unidades de conservacao do CNUC (Ministerio do Meio Ambiente): 3.406 com poligono e 170 so com ponto esquematico (edicao 2026_07). Espelho versionado; carga manual autorizada (o shapefile recente so existe em SharePoint). Ver mma/unidades_conservacao/LEIAME_unidades_conservacao.md.';
COMMENT ON COLUMN vetorial.mma_unidades_conservacao.cd_cnuc IS 'Origem: cd_cnuc. Codigo da UC no CNUC; uma versao vigente por UC.';
COMMENT ON COLUMN vetorial.mma_unidades_conservacao.camada_origem IS 'Derivado: poligonos ou pontos. As 170 UCs de ponto nao tem poligono na edicao (limite so esquematico).';
COMMENT ON COLUMN vetorial.mma_unidades_conservacao.esfera IS 'Origem: esfera. A capitalizacao varia (Federal/federal): compare com lower().';
COMMENT ON COLUMN vetorial.mma_unidades_conservacao.edicao IS 'Edicao do CNUC (AAAA_MM, do nome do zip) em que esta versao da UC entrou.';

INSERT INTO catalogo.mapa_colunas (tabela, coluna, origem, fonte, observacao)
SELECT 'vetorial.mma_unidades_conservacao', c.column_name,
       CASE WHEN c.column_name IN ('camada_origem','ano_criacao','edicao') THEN 'derivado'
            WHEN c.column_name IN ('id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala','geom_origem_texto') THEN 'controle'
            WHEN c.column_name IN ('geom','geom_ponto','longitude_ponto','latitude_ponto') THEN 'geometria'
            WHEN c.column_name = 'nome_abrev' THEN 'NomeAbrev' WHEN c.column_name = 'siscosmar' THEN 'SisCosMar'
            ELSE c.column_name END,
       CASE WHEN c.column_name IN ('camada_origem','ano_criacao','edicao','id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala') THEN 'pipeline'
            ELSE 'MMA' END,
       NULL
FROM information_schema.columns c
WHERE c.table_schema = 'vetorial' AND c.table_name = 'mma_unidades_conservacao'
ON CONFLICT (tabela, coluna) DO UPDATE SET origem = EXCLUDED.origem, fonte = EXCLUDED.fonte;

GRANT SELECT, INSERT, UPDATE, DELETE ON vetorial.mma_unidades_conservacao TO etl;      -- DELETE: so para a rotina de retencao
GRANT SELECT ON vetorial.mma_unidades_conservacao TO leitura, geoserver, analistas;
GRANT MAINTAIN ON vetorial.mma_unidades_conservacao TO etl;

