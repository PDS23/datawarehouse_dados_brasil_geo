-- Cadastro Nacional de Florestas Publicas (CNFP, Servico Florestal Brasileiro) como ESPELHO VERSIONADO: vetorial.sfb_florestas_publicas. Idempotente.
-- Rodar como postgres (o etl so tem DML):
--   .\infra\scripts\dw.ps1 psql -Arquivo sfb\florestas_publicas\sql\01_tabela.sql
--
-- O CNFP junta, num so mapa, as areas publicas com cobertura florestal ou potencial florestal: assentamentos do INCRA (PA, PAE, PDS...), unidades de conservacao
-- (federais, estaduais, municipais), terras indigenas, glebas arrecadadas sem destinacao, areas militares, quilombolas. Uma edicao por ano (hoje 2025).
-- O shapefile NAO tem id: a chave (chave_linha) e a identidade do registro (nome, categoria, classe, uf, geocodigo, ato legal, ano de criacao, orgao), com
-- ordinal so para os raros registros identicos. Mesmas regras das outras fontes vivas: versao vigente = vigente_ate IS NULL; nada e apagado na coleta.

INSERT INTO dim.fontes (nome, sigla, url, descricao)
SELECT 'SFB', 'SFB', 'https://www.gov.br/florestal', 'Servico Florestal Brasileiro - Sistema Nacional de Informacoes Florestais (CNFP: florestas publicas)'
WHERE NOT EXISTS (SELECT 1 FROM dim.fontes WHERE nome = 'SFB');

CREATE TABLE IF NOT EXISTS vetorial.sfb_florestas_publicas (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave_linha       text        NOT NULL,         -- derivado: identidade do registro (a fonte nao tem id); ver LEIAME
    nome              text,                         -- fonte: nome
    categoria         text,                         -- fonte: categoria (sigla: PA, TI, APA, PARNA, FLONA, GLEBA ARRECADADA...; "A / B" quando a area tem dupla afetacao)
    protecao          text,                         -- fonte: protecao (USO SUSTENTAVEL, PROTECAO INTEGRAL, SEM DESTINACAO, USO MILITAR, OUTROS USOS)
    tipo              text,                         -- fonte: tipo (TIPO A = floresta publica destinada; TIPO B = gleba sem destinacao)
    governo           text,                         -- fonte: governo (FEDERAL, ESTADUAL, MUNICIPAL)
    comunitari        text,                         -- fonte: comunitari (SIM/NAO: uso comunitario)
    classe            text,                         -- fonte: classe (ASSENTFED, UCFED, UCEST, UCMUN, TI, GLEBAFED, AREAMILIT...)
    orgao             text,                         -- fonte: orgao (INCRA, FUNAI, ICMBio, orgaos estaduais)
    sobreposic        text,                         -- fonte: sobreposic (SIM/NAO: se sobrepoe a outra area do cadastro)
    atolegal          text,                         -- fonte: atolegal (ato de criacao)
    anocriacao        text,                         -- fonte: anocriacao (formatos mistos: AAAA-MM-DD, DD-MM-AAAA, AAAA/MM/DD hh:mm:ss)
    ano_criacao       smallint,                     -- derivado: ano de anocriacao
    estagio           text,                         -- fonte: estagio
    codigo            text,                         -- fonte: codigo (vazio na edicao 2025)
    observacao        text,                         -- fonte: observacao (vazio na edicao 2025)
    uf                text,                         -- fonte: uf (sigla; uma UF por registro)
    id_estado         smallint    REFERENCES dim.estados (id_estado),   -- derivado de uf
    bioma             text,                         -- fonte: bioma ("A/B" quando cruza biomas)
    municipio         text,                         -- fonte: municipio (lista separada por "/")
    geocodigo         text,                         -- fonte: geocodigo (codigos IBGE dos municipios, separados por "/")
    area_ha           numeric,                      -- fonte: area_ha (hectares)
    geom              geometry(MultiPolygon, 4674), -- fonte: shapefile (SIRGAS 2000; o Z da fonte e descartado). NULL se geom_anomala
    geom_anomala      boolean     NOT NULL DEFAULT false,
    geom_origem_texto text,
    edicao            text        NOT NULL,         -- derivado: edicao do CNFP (ano) em que esta versao entrou
    id_fonte          smallint    NOT NULL REFERENCES dim.fontes (id_fonte),
    importado_em      date        NOT NULL DEFAULT current_date,
    vigente_desde     date        NOT NULL DEFAULT current_date,
    vigente_ate       date,
    coletado_em       timestamptz NOT NULL DEFAULT now(),
    reaberto_em       date
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_sfb_fp_vigente ON vetorial.sfb_florestas_publicas (chave_linha) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_sfb_fp_geom      ON vetorial.sfb_florestas_publicas USING gist (geom) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_sfb_fp_categoria ON vetorial.sfb_florestas_publicas (categoria)       WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_sfb_fp_uf        ON vetorial.sfb_florestas_publicas (id_estado)       WHERE vigente_ate IS NULL;

COMMENT ON TABLE vetorial.sfb_florestas_publicas IS
    'Cadastro Nacional de Florestas Publicas (SFB): assentamentos, UCs, terras indigenas, glebas, areas militares. Espelho versionado, uma edicao por ano (hoje 2025). Ver sfb/florestas_publicas/LEIAME_florestas_publicas.md.';
COMMENT ON COLUMN vetorial.sfb_florestas_publicas.chave_linha IS 'Derivado: o shapefile nao tem id; identidade = nome|categoria|classe|uf|geocodigo|atolegal|anocriacao|orgao (+ ordinal se identicos).';
COMMENT ON COLUMN vetorial.sfb_florestas_publicas.categoria IS 'Origem: categoria. "A / B" = dupla afetacao (ex.: PA / APA).';
COMMENT ON COLUMN vetorial.sfb_florestas_publicas.edicao IS 'Edicao do CNFP (ano) em que esta versao entrou.';

INSERT INTO catalogo.mapa_colunas (tabela, coluna, origem, fonte, observacao)
SELECT 'vetorial.sfb_florestas_publicas', c.column_name,
       CASE WHEN c.column_name IN ('chave_linha','ano_criacao','id_estado','edicao') THEN 'derivado'
            WHEN c.column_name IN ('id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala','geom_origem_texto') THEN 'controle'
            WHEN c.column_name = 'geom' THEN 'geometria' ELSE c.column_name END,
       CASE WHEN c.column_name IN ('chave_linha','ano_criacao','id_estado','edicao','id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala')
            THEN 'pipeline' ELSE 'SFB' END,
       CASE WHEN c.column_name = 'id_estado' THEN 'dim.estados' END
FROM information_schema.columns c
WHERE c.table_schema = 'vetorial' AND c.table_name = 'sfb_florestas_publicas'
ON CONFLICT (tabela, coluna) DO UPDATE SET origem = EXCLUDED.origem, fonte = EXCLUDED.fonte;

GRANT SELECT, INSERT, UPDATE, DELETE ON vetorial.sfb_florestas_publicas TO etl;      -- DELETE: so para a rotina de retencao
GRANT SELECT ON vetorial.sfb_florestas_publicas TO leitura, geoserver, analistas;
GRANT MAINTAIN ON vetorial.sfb_florestas_publicas TO etl;

SELECT 'vetorial.sfb_florestas_publicas' AS item, count(*)::text AS valor FROM vetorial.sfb_florestas_publicas;
