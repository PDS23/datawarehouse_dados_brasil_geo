-- PRODES (desmatamento anual por bioma) como ESPELHO VERSIONADO do INPE, reconstruido do zero pelo pipeline.
-- Rodar como postgres (o etl so tem DML):
--   Get-Content prodes\desmatamento\sql\01_tabela.sql | docker exec -i dw-postgis psql -U postgres -d data_warehouse -v ON_ERROR_STOP=1
-- Idempotente. So ASCII de proposito.
--
-- A tabela nasce no schema de CONSTRUCAO prodes_novo (a vetorial.prodes_desmatamento atual, da carga manual de 2026-09,
-- segue intacta). Depois de carregar e validar, 03_troca.sql move a nova para vetorial e guarda a antiga renomeada.
-- Indices secundarios e chaves estrangeiras so depois da carga (02_indices_chaves.sql): carregar com eles e bem mais lento.
--
-- Regras (decididas com o usuario em 2026-10-21): igual ao SICAR. O banco e um espelho do INPE; cada feicao (uuid) tem
-- versoes (vigente_desde/vigente_ate); feicao que o INPE retira tem a versao fechada (nada e apagado), e vigente = o que o
-- INPE publica hoje. Colunas com os nomes da fonte (year, main_class, area_km...), texto sempre `text`.

CREATE SCHEMA IF NOT EXISTS prodes_novo;

CREATE TABLE IF NOT EXISTS prodes_novo.prodes_desmatamento (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid              text        NOT NULL,                 -- INPE: uuid (chave estavel da feicao entre edicoes; com o bioma identifica a feicao)
    bioma             text        NOT NULL,                 -- derivado: arquivo de origem (amazonia, caatinga, cerrado, mata_atlantica, pampa, pantanal)
    camada_origem     text        NOT NULL,                 -- derivado: camada do GeoPackage (yearly_deforestation, ..._biome, ..._nf_biome)
    id_bioma          smallint    NOT NULL,                 -- derivado de bioma (dim.biomas)
    state             text,                                 -- INPE: state (sigla ou nome do estado, como entregue)
    id_estado         smallint,                             -- derivado de state (dim.estados); NULL se nao casar
    path_row          text,                                 -- INPE: path_row (orbita/ponto Landsat)
    main_class        text,                                 -- INPE: main_class (a capitalizacao varia entre edicoes: compare com lower())
    class_name        text,                                 -- INPE: class_name (dAAAA)
    def_cloud         double precision,                     -- INPE: def_cloud
    julian_day        integer,                              -- INPE: julian_day
    image_date        date,                                 -- INPE: image_date
    year              integer,                              -- INPE: year (ano PRODES)
    area_km           double precision,                     -- INPE: area_km (km2)
    scene_id          integer,                              -- INPE: scene_id
    source            text,                                 -- INPE: source
    satellite         text,                                 -- INPE: satellite
    sensor            text,                                 -- INPE: sensor
    geom              geometry(MultiPolygon, 4674),         -- INPE: geometria (SIRGAS 2000). NULL quando geom_anomala
    geom_anomala      boolean     NOT NULL DEFAULT false,   -- true = caixa fora do Brasil (ex.: X/Y trocados) ou sem geometria
    geom_origem_texto text,                                 -- EWKT como o INPE entregou, SO quando geom_anomala
    id_fonte          smallint    NOT NULL,
    importado_em      date        NOT NULL DEFAULT current_date,
    vigente_desde     date        NOT NULL DEFAULT current_date,
    vigente_ate       date,
    coletado_em       timestamptz NOT NULL DEFAULT now(),
    edicao            text        NOT NULL,                 -- vAAAAMMDD do arquivo do INPE em que esta versao entrou
    reaberto_em       date                                  -- data em que o INPE republicou a feicao identica e a versao foi reaberta
);
ALTER TABLE prodes_novo.prodes_desmatamento ADD COLUMN IF NOT EXISTS reaberto_em date;
CREATE UNIQUE INDEX IF NOT EXISTS uq_prodes_desmatamento_vigente ON prodes_novo.prodes_desmatamento (bioma, uuid) WHERE vigente_ate IS NULL;

COMMENT ON TABLE prodes_novo.prodes_desmatamento IS
    'PRODES: poligonos de desmatamento anual por bioma (yearly_deforestation; Amazonia tambem a nao-floresta), espelho do INPE/TerraBrasilis. Historico por versao: vigente = vigente_ate IS NULL. Ver prodes/desmatamento/LEIAME_prodes_desmatamento.md.';
COMMENT ON COLUMN prodes_novo.prodes_desmatamento.uuid IS 'Origem: INPE uuid. Estavel entre edicoes; uma versao vigente por (bioma, uuid). O mesmo uuid pode aparecer em dois biomas (poligonos de divisa publicados nos dois arquivos).';
COMMENT ON COLUMN prodes_novo.prodes_desmatamento.main_class IS 'Origem: INPE main_class. A edicao de 2026-10 da Amazonia traz minusculas (desmatamento); use lower().';
COMMENT ON COLUMN prodes_novo.prodes_desmatamento.geom_anomala IS 'true = o INPE entregou a feicao com a caixa fora do Brasil (lon -75..-28, lat -35..6) ou sem geometria; o original esta em geom_origem_texto.';
COMMENT ON COLUMN prodes_novo.prodes_desmatamento.edicao IS 'Versao (vAAAAMMDD) do GeoPackage do INPE em que esta versao da feicao entrou.';

-- catalogo.coletas (criada pelo SICAR) ganha a edicao da fonte, para o pipeline pular o que ja foi carregado
ALTER TABLE catalogo.coletas ADD COLUMN IF NOT EXISTS edicao text;
ALTER TABLE catalogo.coletas ADD COLUMN IF NOT EXISTS reabertos bigint;      -- versoes reabertas (feicao retirada e republicada identica)

