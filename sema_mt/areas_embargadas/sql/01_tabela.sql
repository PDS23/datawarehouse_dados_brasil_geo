-- Areas embargadas e desembargadas da SEMA-MT (Secretaria de Estado de Meio Ambiente de Mato Grosso) como ESPELHOS VERSIONADOS. Idempotente.
-- Rodar como postgres (o etl so tem DML):
--   .\infra\scripts\dw.ps1 psql -Arquivo sema_mtreas_embargadas\sql_tabela.sql
--
-- Duas tabelas, uma por camada da fonte, com o MESMO esquema (assim ninguem confunde embargo vigente com embargo encerrado):
--   vetorial.sema_mt_areas_embargadas     (camada AREAS_EMBARGADAS_SEMA)
--   vetorial.sema_mt_areas_desembargadas  (camada AREAS_DESEMBARGADAS_SEMA)
-- Uma linha por POLIGONO. A camada nao tem id unico (varios poligonos por termo de embargo): chave_linha = identidade do registro + ordinal nos identicos.
-- DADO PESSOAL (mesma decisao do IBAMA e do ICMBio): nome como a fonte publica; CPF de pessoa fisica NAO e guardado, so o HMAC-SHA256 (mesma chave); CNPJ como vem.
-- NAO publicar estas tabelas no GeoServer sem tirar `nome`.

INSERT INTO dim.fontes (nome, sigla, url, descricao)
SELECT 'SEMA-MT', 'SEMA-MT', 'https://www.sema.mt.gov.br', 'Secretaria de Estado de Meio Ambiente de Mato Grosso (areas embargadas e desembargadas)'
WHERE NOT EXISTS (SELECT 1 FROM dim.fontes WHERE nome = 'SEMA-MT');

CREATE TABLE IF NOT EXISTS vetorial.sema_mt_areas_embargadas (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave_linha        text        NOT NULL,         -- derivado: identidade do poligono (a camada nao tem id unico); ver LEIAME
    objectid           bigint,                       -- fonte: OBJECTID (nao entra na comparacao)
    nome               text,                         -- fonte: NOME (nome do embargado; dado pessoal como a fonte publica)
    cpf_cnpj           text,                         -- fonte: CPF_CNPJ. CPF de pessoa fisica NAO e guardado (NULL); CNPJ (so digitos) e texto livre entram como vem
    tipo_doc_embargado text,                         -- derivado: CPF, CNPJ, OUTRO ou NULL (sem documento)
    doc_valido         boolean,                      -- derivado: digitos verificadores do CPF/CNPJ conferem
    cpf_embargado_hash text,                         -- derivado: HMAC-SHA256 dos 11 digitos do CPF (so se tipo_doc_embargado = CPF); mesma chave do IBAMA e do ICMBio
    propriedad         text,                         -- fonte: PROPRIEDAD (nome da propriedade)
    dano               text,                         -- fonte: DANO
    ano_desmat         text,                         -- fonte: ANO_DESMAT
    a_infrac           text,                         -- fonte: A_INFRAC (numero do auto de infracao)
    t_embargo          text,                         -- fonte: T_EMBARGO (numero do termo de embargo)
    dat_lavrat         text,                         -- fonte: DAT_LAVRAT (DD/MM/AAAA; ha datas incompletas como 00/07/2017)
    data_lavratura     date,                         -- derivado: dat_lavrat como date (NULL se incompleta ou invalida)
    n_processo         text,                         -- fonte: N_PROCESSO
    coord_x            text,                         -- fonte: COORD_X (longitude em graus, minutos e segundos, texto)
    coord_y            text,                         -- fonte: COORD_Y (latitude em graus, minutos e segundos, texto)
    fonte              text,                         -- fonte: FONTE (setor da SEMA que registrou)
    obs                text,                         -- fonte: OBS
    area_ha            numeric,                      -- fonte: AREA_HA
    geom               geometry(MultiPolygon, 4674), -- fonte: geometria da camada (SIRGAS 2000). NULL se geom_anomala
    geom_anomala       boolean     NOT NULL DEFAULT false,
    geom_origem_texto  text,
    id_fonte           smallint    NOT NULL REFERENCES dim.fontes (id_fonte),
    importado_em       date        NOT NULL DEFAULT current_date,
    vigente_desde      date        NOT NULL DEFAULT current_date,
    vigente_ate        date,
    coletado_em        timestamptz NOT NULL DEFAULT now(),
    reaberto_em        date
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_sema_mt_areas_embargadas_vigente ON vetorial.sema_mt_areas_embargadas (chave_linha) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_sema_mt_areas_embargadas_geom ON vetorial.sema_mt_areas_embargadas USING gist (geom) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_sema_mt_areas_embargadas_hash ON vetorial.sema_mt_areas_embargadas (cpf_embargado_hash) WHERE vigente_ate IS NULL AND cpf_embargado_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_sema_mt_areas_embargadas_cnpj ON vetorial.sema_mt_areas_embargadas (cpf_cnpj) WHERE vigente_ate IS NULL AND cpf_cnpj IS NOT NULL;

COMMENT ON TABLE vetorial.sema_mt_areas_embargadas IS
    'Areas embargadas da SEMA-MT (camada AREAS_EMBARGADAS_SEMA). Espelho versionado, uma linha por poligono. Dado pessoal: CPF so como HMAC, nome como a fonte publica; nao publicar no GeoServer sem tirar nome. Ver sema_mt/areas_embargadas/LEIAME_areas_embargadas.md.';
COMMENT ON COLUMN vetorial.sema_mt_areas_embargadas.chave_linha IS 'Derivado: a camada nao tem id unico; identidade = t_embargo|n_processo|a_infrac|documento|propriedad|dat_lavrat|ano_desmat (+ ordinal se identicos).';
COMMENT ON COLUMN vetorial.sema_mt_areas_embargadas.cpf_cnpj IS 'Origem: CPF_CNPJ. CPF de pessoa fisica nao e guardado (NULL; ver cpf_embargado_hash).';

INSERT INTO catalogo.mapa_colunas (tabela, coluna, origem, fonte, observacao)
SELECT 'vetorial.sema_mt_areas_embargadas', c.column_name,
       CASE WHEN c.column_name IN ('chave_linha','tipo_doc_embargado','doc_valido','cpf_embargado_hash','data_lavratura') THEN 'derivado'
            WHEN c.column_name IN ('id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala','geom_origem_texto') THEN 'controle'
            WHEN c.column_name = 'geom' THEN 'geometria' ELSE upper(c.column_name) END,
       CASE WHEN c.column_name IN ('chave_linha','tipo_doc_embargado','doc_valido','cpf_embargado_hash','data_lavratura','id','id_fonte','importado_em','vigente_desde',
                                   'vigente_ate','coletado_em','reaberto_em','geom_anomala') THEN 'pipeline' ELSE 'SEMA-MT' END,
       CASE WHEN c.column_name = 'cpf_embargado_hash' THEN 'HMAC-SHA256 com a mesma chave do IBAMA' END
FROM information_schema.columns c
WHERE c.table_schema = 'vetorial' AND c.table_name = 'sema_mt_areas_embargadas'
ON CONFLICT (tabela, coluna) DO UPDATE SET origem = EXCLUDED.origem, fonte = EXCLUDED.fonte;

GRANT SELECT, INSERT, UPDATE, DELETE ON vetorial.sema_mt_areas_embargadas TO etl;      -- DELETE: so para a rotina de retencao
GRANT SELECT ON vetorial.sema_mt_areas_embargadas TO leitura, geoserver, analistas;
GRANT MAINTAIN ON vetorial.sema_mt_areas_embargadas TO etl;

