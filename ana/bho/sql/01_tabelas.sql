-- Base Hidrografica Ottocodificada 1:250.000 (BHO250, ANA) como ESPELHOS VERSIONADOS: 4 tabelas em vetorial. Idempotente.
-- Rodar como postgres (o etl so tem DML):
--   .\infra\scripts\dw.ps1 psql -Arquivo ana\bho\sql\01_tabelas.sql
--
-- ana_bho_trechos_drenagem (cotrecho), ana_bho_cursos_dagua (idcda), ana_bho_linha_costa (colinhacosta), ana_bho_bacias_otto (nivel + wts_pk, 6 niveis numa tabela so).
-- A fonte tem chaves repetidas (31 trechos, 15 cursos, os 25 segmentos da costa): chave_linha = campos da chave + ordinal (#2...) nas repeticoes. Colunas com os nomes da fonte em minusculas. Mesmas regras das outras fontes vivas: vigente = vigente_ate IS NULL; nada e apagado na coleta.

INSERT INTO dim.fontes (nome, sigla, url, descricao)
SELECT 'ANA', 'ANA', 'https://www.gov.br/ana', 'Agencia Nacional de Aguas e Saneamento Basico'
WHERE NOT EXISTS (SELECT 1 FROM dim.fontes WHERE nome = 'ANA');

CREATE TABLE IF NOT EXISTS vetorial.ana_bho_trechos_drenagem (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave_linha       text        NOT NULL,               -- derivado: chave da feicao (campos da chave separados por |; "#2", "#3" nas repeticoes que a fonte traz)
    drn_pk                            integer,           -- fonte: drn_pk - Identificador do registro no banco da ANA.
    cotrecho                          integer,           -- fonte: cotrecho - Código do trecho de drenagem (chave).
    noorigem                          integer,           -- fonte: noorigem - Nó de origem (montante) do trecho.
    nodestino                         integer,           -- fonte: nodestino - Nó de destino (jusante) do trecho.
    cocursodag                        text,              -- fonte: cocursodag - Código do curso d'água (codificação de Otto Pfafstetter).
    cobacia                           text,              -- fonte: cobacia - Código da ottobacia do trecho.
    nucomptrec                        double precision,  -- fonte: nucomptrec - Comprimento do trecho, em km.
    nudistbact                        double precision,  -- fonte: nudistbact - Distância do trecho até a foz da bacia, em km.
    nudistcdag                        double precision,  -- fonte: nudistcdag - Distância do trecho até o fim do curso d'água, em km.
    nuareacont                        double precision,  -- fonte: nuareacont - Área de contribuição do trecho, em km².
    nuareamont                        double precision,  -- fonte: nuareamont - Área a montante do trecho, em km².
    nogenerico                        text,              -- fonte: nogenerico - Nome genérico do curso d'água (rio, riacho, córrego...).
    noligacao                         text,              -- fonte: noligacao - Nome de ligação.
    noespecif                         text,              -- fonte: noespecif - Nome específico do curso d'água.
    noriocomp                         text,              -- fonte: noriocomp - Nome completo do rio.
    nooriginal                        text,              -- fonte: nooriginal - Nome original na base cartográfica.
    cocdadesag                        text,              -- fonte: cocdadesag - Código do curso d'água em que este desagua.
    nutrjus                           integer,           -- fonte: nutrjus - Código do trecho a jusante.
    nudistbacc                        double precision,  -- fonte: nudistbacc - Distância do curso d'água até a foz da bacia, em km.
    nuareabacc                        double precision,  -- fonte: nuareabacc - Área da bacia do curso d'água, em km².
    nuordemcda                        integer,           -- fonte: nuordemcda - Ordem do curso d'água na codificação de Otto.
    nucompcda                         double precision,  -- fonte: nucompcda - Comprimento do curso d'água, em km.
    nunivotto                         integer,           -- fonte: nunivotto - Nível de codificação Otto do trecho.
    nunivotcda                        integer,           -- fonte: nunivotcda - Nível de codificação Otto do curso d'água.
    nustrahler                        integer,           -- fonte: nustrahler - Ordem de Strahler do trecho.
    dedominial                        text,              -- fonte: dedominial - Dominialidade do curso d'água (federal, estadual...).
    dsversao                          text,              -- fonte: dsversao - Versão da base hidrográfica.
    geom              geometry(MultiLineString, 4674),    -- fonte: geopackage da ANA (SIRGAS 2000). NULL se geom_anomala
    geom_anomala      boolean     NOT NULL DEFAULT false,
    geom_origem_texto text,
    edicao            text        NOT NULL,                -- derivado: versao da BHO em que esta versao entrou (do nome do arquivo completo, ex.: 02_03)
    id_fonte          smallint    NOT NULL REFERENCES dim.fontes (id_fonte),
    importado_em      date        NOT NULL DEFAULT current_date,
    vigente_desde     date        NOT NULL DEFAULT current_date,
    vigente_ate       date,
    coletado_em       timestamptz NOT NULL DEFAULT now(),
    reaberto_em       date
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_ana_bho_trechos_drenagem_vigente ON vetorial.ana_bho_trechos_drenagem (chave_linha) WHERE vigente_ate IS NULL;
CREATE INDEX IF NOT EXISTS ix_ana_bho_trechos_drenagem_geom ON vetorial.ana_bho_trechos_drenagem USING gist (geom) WHERE vigente_ate IS NULL;
COMMENT ON TABLE vetorial.ana_bho_trechos_drenagem IS 'Trechos de drenagem da BHO 1:250.000 (ANA). Trechos de drenagem da Base Hidrográfica Ottocodificada 1:250.000: a rede de rios em linhas, cada trecho com o código da ottobacia e do curso d''água. Espelho versionado. Ver ana/bho/LEIAME_bho.md.';
COMMENT ON COLUMN vetorial.ana_bho_trechos_drenagem.edicao IS 'Versao da BHO em que esta versao entrou (ex.: 02_03).';

INSERT INTO catalogo.mapa_colunas (tabela, coluna, origem, fonte, observacao)
SELECT 'vetorial.ana_bho_trechos_drenagem', c.column_name,
       CASE WHEN c.column_name IN ('edicao', 'chave_linha') THEN 'derivado'
            WHEN c.column_name IN ('id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala','geom_origem_texto') THEN 'controle'
            WHEN c.column_name = 'geom' THEN 'geometria' ELSE c.column_name END,
       CASE WHEN c.column_name IN ('edicao','chave_linha','id','id_fonte','importado_em','vigente_desde','vigente_ate','coletado_em','reaberto_em','geom_anomala') THEN 'pipeline' ELSE 'ANA' END, NULL
FROM information_schema.columns c WHERE c.table_schema = 'vetorial' AND c.table_name = 'ana_bho_trechos_drenagem'
ON CONFLICT (tabela, coluna) DO UPDATE SET origem = EXCLUDED.origem, fonte = EXCLUDED.fonte;

GRANT SELECT, INSERT, UPDATE, DELETE ON vetorial.ana_bho_trechos_drenagem TO etl;      -- DELETE: so para a rotina de retencao
GRANT SELECT ON vetorial.ana_bho_trechos_drenagem TO leitura, geoserver, analistas;
GRANT MAINTAIN ON vetorial.ana_bho_trechos_drenagem TO etl;

